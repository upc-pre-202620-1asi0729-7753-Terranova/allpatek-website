let currentLang = DEFAULT_LANG;
const KEY_RE = /\{([a-z0-9.]+)\}/gi;
const ATTRS = ["placeholder", "aria-label", "alt", "title"];

function $(selector, root = document) {
  return root.querySelector(selector);
}

function t(key) {
  return MESSAGES[currentLang][key] || MESSAGES[DEFAULT_LANG][key] || key;
}

// Replaces {clave} with the text of the active language
function fillKeys(text) {
  return text.replace(KEY_RE, (_, key) => t(key));
}

function applyTranslations(lang) {
  if (!MESSAGES[lang]) return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang === "es_419" ? "es-419" : "en";

  // 1) Text nodes: keep the original {clave} template to allow language switching
  document.querySelectorAll("body, body *").forEach((el) => {
    if (el.closest("script, style")) return;

    el.childNodes.forEach((node) => {
      if (node.nodeType !== Node.TEXT_NODE) return;
      if (!node._i18nTpl && !/\{[a-z0-9.]+\}/i.test(node.nodeValue)) return;
      if (!node._i18nTpl) node._i18nTpl = node.nodeValue;
      node.nodeValue = fillKeys(node._i18nTpl);
    });
  });

  // 2) Attributes that can contain {clave}
  document.querySelectorAll("body *").forEach((el) => {
    ATTRS.forEach((attr) => {
      const current = el.getAttribute(attr);
      if (!current) return;

      const storeKey = `_i18n_${attr}`;
      if (!el[storeKey] && !/\{[a-z0-9.]+\}/i.test(current)) return;
      if (!el[storeKey]) el[storeKey] = current;
      el.setAttribute(attr, fillKeys(el[storeKey]));
    });
  });

  // 3) <title> in <head>
  const titleEl = document.querySelector("title");
  if (titleEl) {
    if (!titleEl._i18nTpl) titleEl._i18nTpl = titleEl.textContent;
    document.title = fillKeys(titleEl._i18nTpl);
  }

  document.querySelectorAll(".lang__btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
}

function initI18n() {
  const saved = localStorage.getItem(STORAGE_KEY);
  const lang = MESSAGES[saved] ? saved : DEFAULT_LANG;
  applyTranslations(lang);

  document.querySelectorAll(".lang__btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyTranslations(btn.getAttribute("data-lang"));
    });
  });
}

/* ========== Navbar ========== */
const SCROLL_OFFSET = 24;

function setMenuOpen(nav, menu, toggle, isOpen) {
  menu.classList.toggle("is-open", isOpen);
  nav.classList.toggle("is-open", isOpen);
  toggle.setAttribute("aria-expanded", String(isOpen));
}

function initNavbar() {
  const nav = $(".nav");
  const menu = $("#nav-menu");
  const toggle = $(".nav__toggle");
  if (!nav || !menu || !toggle) return;

  const paintOnScroll = () => {
    nav.classList.toggle("is-scrolled", window.scrollY > SCROLL_OFFSET);
  };

  paintOnScroll();
  window.addEventListener("scroll", paintOnScroll, { passive: true });

  toggle.addEventListener("click", () => {
    setMenuOpen(nav, menu, toggle, !menu.classList.contains("is-open"));
  });

  menu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => setMenuOpen(nav, menu, toggle, false));
  });
}

/* ========== Contact form ========== */
const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function isValidField(input) {
  const value = input.value.trim();
  if (!value) return false;
  if (input.type === "email") return EMAIL_PATTERN.test(value);
  return true;
}

function showFormStatus(statusEl, message, type) {
  statusEl.textContent = message;
  statusEl.className = `form__status form__status--${type}`;
}

function initContactForm() {
  const form = $("#contact-form");
  const statusEl = $(".form__status");
  if (!form || !statusEl) return;

  form.addEventListener("submit", (event) => {
    event.preventDefault();

    const fields = [...form.querySelectorAll("input")];
    let isValid = true;

    fields.forEach((input) => {
      const ok = isValidField(input);
      input.closest("label")?.classList.toggle("is-invalid", !ok);
      if (!ok) isValid = false;
    });

    if (!isValid) {
      showFormStatus(statusEl, t("contact.error"), "error");
      return;
    }

    showFormStatus(statusEl, t("contact.ok"), "ok");
    form.reset();
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initI18n();
  initNavbar();
  initContactForm();
});
